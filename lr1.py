"""
============================================================
Задание: Сумма и количество чисел (цикл while)
============================================================
Вводите целые числа по одному, завершите ввод числом 0.
Находит сумму всех чисел и их количество.
"""

total_sum = 0
count_elements = 0

print("Вводите целые числа по одному, завершите ввод числом 0:")

while True:
    number = int(input())
    
    if number == 0:
        break
    
    total_sum += number
    count_elements += 1

print(f"\nРезультаты:")
print(f"а) Сумма всех чисел: {total_sum}")
print(f"б) Количество чисел: {count_elements}")


