import time
from abc import ABC, abstractmethod # Для демонстрации абстракции

# -----------------------------------------------------------------------------
# 1. ИНКАПСУЛЯЦИЯ (Encapsulation)
# В классе скрываются внутренние данные и методы, доступны только через публичные интерфейсы.
# Как описано в файле: "Класс как капсула, которая внутри себя скрывает огромные количество узлов"
# -----------------------------------------------------------------------------

class BaseTelecomDevice(ABC):
    """Базовый класс телекоммуникационного устройства (Абстракция)."""
    
    # Инкапсуляция: используем имя с подчёркиванием для атрибутов, 
    # которые должны быть скрыты извне ("недоступны напрямую извне").
    def __init__(self, device_name: str, ip_address: str, manufacturer: str):
        self._name = device_name       # Приватное/защищённое свойство
        self._ip = ip_address          # Приватное/защищённое свойство
        self._manufacturer = manufacturer
        
        # "Магический" метод __str__ для удобного вывода (как описано в разделе 3)
    def __str__(self):
        return f"Устройство: {self._name} | IP: {self._ip}"

# -----------------------------------------------------------------------------
# 2. НАСЛЕДОВАНИЕ (Inheritance)
# Выносим общее для разных устройств в базовый класс BaseTelecomDevice.
# Расширяем функциональность дочерними классами (как пример Figure -> Line, Rect).
# -----------------------------------------------------------------------------

class Router(BaseTelecomDevice):
    """Маршрутизатор — специфическое устройство."""
    
    def __init__(self, device_name: str, ip_address: str, manufacturer: str):
        super().__init__(device_name, ip_address, manufacturer) # Вызов конструктора родителя
        self._interfaces = [] # Дополнительные свойства дочернего класса

    def add_interface(self, name: str):
        """Добавление интерфейса — расширение функциональности."""
        self._interfaces.append(name)
        return f"Интерфейс {name} добавлен."

class Switch(BaseTelecomDevice):
    """Коммутатор — специфическое устройство."""
    
    def __init__(self, device_name: str, ip_address: str, manufacturer: str):
        super().__init__(device_name, ip_address, manufacturer)
        self._ports = 0 # Дополнительные свойства дочернего класса

    def connect_port(self, count: int):
        """Подключение портов."""
        self._ports += count
        return f"Подключено {count} новых портов."

# -----------------------------------------------------------------------------
# 3. ПОЛИМОРФИЗМ (Polymorphism)
# Возможность работать с разными типами данных через единый базовый класс.
# Как в примере файла: список объектов типа Figure, вызываем draw() и работает метод соответствующего класса.
# Здесь: список устройств, вызываем show_status().
# -----------------------------------------------------------------------------

class TelecomSystemManager:
    """Класс-менеджер системы (управление объектами, хранение данных)."""
    
    def __init__(self):
        self._devices = [] # Хранение объектов

    def add_device(self, device):
        """Добавление устройства. Работает с любым наследником BaseTelecomDevice."""
        self._devices.append(device)
        print(f"[{device.__class__.__name__}] {device._name} добавлен в сеть.")

    def system_status_check(self):
        """Полиморфная функция: вызывает метод для каждого типа устройства."""
        print("\n--- Отчёт о системе ---")
        for device in self._devices:
            # Вызываем абстрактный/общий метод, реализация которого разнится в классах (полиморфизм)
            if hasattr(device, 'show_status'):
                print(device.show_status())
            else:
                print(f"Статус недоступен для {device}")

# -----------------------------------------------------------------------------
# 4. ИСПОЛЬЗОВАНИЕ ПРИНЦИПОВ (Пример работы программы)
# Демонстрация создания приложений на основе ООП, охватывающего управление объектами.
# -----------------------------------------------------------------------------

def main():
    print("=== Телекоммуникационная Система: Лабораторная работа №4 ===\n")
    
    # Создаем менеджер системы
    system = TelecomSystemManager()

    # Создаем объекты (инкапсуляция и наследование в действии)
    # Конкретные устройства создаются по образу класса BaseTelecomDevice
    r1 = Router("Core-Router-01", "192.168.1.1", "Cisco")
    sw1 = Switch("Main-Switch-A", "192.168.1.254", "HPE")
    
    # Добавление в систему (Полиморфизм)
    system.add_device(r1)
    system.add_device(sw1)
    
    # Расширение функциональности (методы дочерних классов)
    r1.add_interface("GigabitEthernet0/0")
    sw1.connect_port(48)

    print("\n--- Проверка полиморфного интерфейса ---")
    system.system_status_check()

if __name__ == "__main__":
    main()
